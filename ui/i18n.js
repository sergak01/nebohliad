let currentLang = 'uk';
const langListeners = [];
// Current global shortcuts { id: accelerator } ('' = off), from main.
let shortcutKeys = {};

const KEY_NAMES = { Control: 'Ctrl', Super: 'Win', Up: '↑', Down: '↓', Left: '←', Right: '→', Space: 'Space' };

// "Control+Alt+Up" → "Ctrl+Alt+↑"; '' → ''.
function keyLabel(accelerator) {
  if (!accelerator) return '';
  return accelerator
    .split('+')
    .map((part) => KEY_NAMES[part] || part.replace(/^num/, 'Num '))
    .join('+');
}

// The current keys of shortcut ids ("" when all are off).
function shortcutLabel(...ids) {
  return ids
    .map((id) => keyLabel(shortcutKeys[id]))
    .filter(Boolean)
    .join(' / ');
}

// Strings mark shortcuts as {key:id} or {key:id1,id2}: " (Ctrl+Alt+H)", or
// nothing when the shortcut is off.
function t(key) {
  const text = STRINGS[currentLang]?.[key] ?? STRINGS.uk[key] ?? key;
  return text.replace(/\{key:([\w,]+)\}/g, (_match, ids) => {
    const label = shortcutLabel(...ids.split(','));
    return label ? ` (${label})` : '';
  });
}

function applyI18n(lang) {
  currentLang = STRINGS[lang] ? lang : 'uk';
  document.documentElement.lang = currentLang;
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of document.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  for (const listener of langListeners) listener(currentLang);
}

// Message for a failed search (search box and location search).
function searchErrorText(error) {
  const message = String(error?.message || error).replace(/^Error invoking remote method '[^']+': (Error: )?/, '');
  return message.includes('GEOCODER_DISABLED') ? t('search.disabled') : `${t('search.error')}: ${message}`;
}

// Calls `listener` after every language change (for strings set from code).
function onLangChange(listener) {
  langListeners.push(listener);
}

overlay.on('ui:lang', applyI18n);
overlay.on('ui:shortcuts', (keys) => {
  shortcutKeys = keys || {};
  applyI18n(currentLang);
});
Promise.all([overlay.invoke('ui:get-lang'), overlay.invoke('ui:get-shortcuts')]).then(([lang, keys]) => {
  shortcutKeys = keys || {};
  applyI18n(lang);
});
